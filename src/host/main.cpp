/*
 * main.cpp - Host-Side Orchestrator for DPA Packet Mirroring
 *
 * Runs on host (x86_64 in NIC mode) or ARM cores of BlueField-3 (DPU mode).
 * Sets up DPA queues, event handlers, DevX flow steering, and monitors execution.
 */

#include <iostream>
#include <string>
#include <vector>
#include <atomic>
#include <csignal>
#include <chrono>
#include <thread>
#include <cstring>
#include <endian.h>

#include <CLI/CLI.hpp>
#include <infiniband/verbs.h>
#include <infiniband/mlx5dv.h>
#include <libflexio/flexio.h>
#include <libflexio/flexio_ver.h>

#include "dpa_mirror_com.h"
#include "flow_steering.hpp"

// DPA device entry point symbol (generated by DPACC)
extern "C" flexio_func_t dpa_mirror_handler;

namespace {

constexpr size_t Q_DEPTH = (1ULL << LOG_CQ_DEPTH);
constexpr size_t CQE_BSIZE = 64;
constexpr size_t CQ_BSIZE = Q_DEPTH * CQE_BSIZE;

constexpr size_t LOG_WQ_WQE_BSIZE = 6; // 64 bytes per WQE
constexpr size_t WQ_WQE_BSIZE = (1ULL << LOG_WQ_WQE_BSIZE);
constexpr size_t WQ_RING_BSIZE = Q_DEPTH * WQ_WQE_BSIZE;

constexpr size_t Q_DATA_ENTRY_BSIZE = WQD_CHUNK_BSIZE; // 2048 bytes
constexpr size_t Q_DATA_BSIZE = Q_DEPTH * Q_DATA_ENTRY_BSIZE;

constexpr size_t MSG_HOST_BUFF_BSIZE = (512 * (1ULL << FLEXIO_MSG_DEV_LOG_DATA_CHUNK_BSIZE));

std::atomic<bool> g_stop_requested{false};

void signal_handler(int) {
    g_stop_requested = true;
}

} // namespace

class DpaMirrorApp {
public:
    DpaMirrorApp(std::string device_name, uint16_t udp_port, bool nic_mode, uint64_t client_dmac)
        : device_name_(std::move(device_name)),
          udp_port_(udp_port),
          nic_mode_(nic_mode),
          client_dmac_(client_dmac) {}

    ~DpaMirrorApp() {
        teardown();
    }

    bool initialize() {
        std::cout << "[Host] Initializing FlexIO version...\n";
        if (flexio_version_set(FLEXIO_VER_USED)) {
            std::cerr << "[Host] Failed to set FlexIO API version\n";
            return false;
        }

        std::cout << "[Host] Opening IB device: " << device_name_ << "...\n";
        if (!open_device()) {
            return false;
        }

        std::cout << "[Host] Loading DPA application 'dpa_mirror_app'...\n";
        struct flexio_app_select_attr app_sel_attr = {};
        app_sel_attr.app_name = "dpa_mirror_app";
        app_sel_attr.hw_model_id = FLEXIO_HW_MODEL_DEF;
        app_sel_attr.ibv_ctx = ibv_ctx_;

        if (flexio_app_get(&app_sel_attr, &flexio_app_)) {
            std::cerr << "[Host] Failed to get DPA application. Make sure DPA device archive is linked.\n";
            return false;
        }

        if (flexio_process_create(ibv_ctx_, flexio_app_, nullptr, &flexio_process_)) {
            std::cerr << "[Host] Failed to create FlexIO process on DPA\n";
            return false;
        }

        process_pd_ = flexio_process_get_pd(flexio_process_);
        process_uar_ = flexio_process_get_uar(flexio_process_);

        uint64_t udbg_token = flexio_process_udbg_token_get(flexio_process_);
        if (udbg_token) {
            std::cout << "[Host] Debug token: 0x" << std::hex << udbg_token << std::dec << "\n";
        }

        // Setup DPA message stream for printfs
        struct flexio_msg_stream_attr stream_attr = {};
        stream_attr.data_bsize = MSG_HOST_BUFF_BSIZE;
        stream_attr.sync_mode = FLEXIO_MSG_DEV_SYNC_MODE_SYNC;
        stream_attr.level = FLEXIO_MSG_DEV_INFO;
        stream_attr.transport_mode = FLEXIO_MSG_TRANSPORT_QP_RC;

        if (flexio_msg_stream_create(flexio_process_, &stream_attr, stdout, nullptr, &msg_stream_)) {
            std::cerr << "[Host] Failed to create DPA messaging stream\n";
            return false;
        }

        // Setup Event Handler
        if (!create_event_handler()) {
            return false;
        }

        // Setup SQ and RQ
        if (!create_sq() || !create_rq()) {
            return false;
        }

        // Setup Flow Steering
        if (!setup_steering()) {
            return false;
        }

        // Copy host configuration to DPA memory
        if (!copy_config_to_dpa()) {
            return false;
        }

        return true;
    }

    bool run() {
        std::cout << "[Host] Starting DPA Event Handler...\n";
        if (flexio_event_handler_run(event_handler_, app_data_daddr_)) {
            std::cerr << "[Host] Failed to start event handler\n";
            return false;
        }

        std::cout << "\n======================================================\n";
        std::cout << "  DPA Packet Mirror is RUNNING on " << device_name_ << "\n";
        std::cout << "  Steering UDP Port: " << udp_port_ << "\n";
        std::cout << "  Mode: " << (nic_mode_ ? "NIC / Host Mode" : "DPU Mode (ARM SoC)") << "\n";
        std::cout << "  Press Ctrl+C to terminate\n";
        std::cout << "======================================================\n\n";

        while (!g_stop_requested) {
            std::this_thread::sleep_for(std::chrono::milliseconds(200));
        }

        std::cout << "\n[Host] Stopping DPA service...\n";
        return true;
    }

private:
    bool open_device() {
        int num_devices = 0;
        struct ibv_device **dev_list = ibv_get_device_list(&num_devices);
        if (!dev_list || num_devices == 0) {
            std::cerr << "[Host] No InfiniBand devices found.\n";
            return false;
        }

        struct ibv_device *target_dev = nullptr;
        for (int i = 0; i < num_devices; ++i) {
            if (device_name_ == ibv_get_device_name(dev_list[i])) {
                target_dev = dev_list[i];
                break;
            }
        }

        if (!target_dev) {
            std::cerr << "[Host] Device '" << device_name_ << "' not found.\n";
            ibv_free_device_list(dev_list);
            return false;
        }

        ibv_ctx_ = ibv_open_device(target_dev);
        ibv_free_device_list(dev_list);

        if (!ibv_ctx_) {
            std::cerr << "[Host] Failed to open IB device context.\n";
            return false;
        }
        return true;
    }

    bool alloc_cq_mem(struct app_transfer_cq &cq_transf) {
        __be32 dbr[2] = {0, 0};
        if (flexio_copy_from_host(flexio_process_, dbr, sizeof(dbr), &cq_transf.cq_dbr_daddr)) {
            std::cerr << "[Host] Failed to allocate CQ DBR on DPA heap\n";
            return false;
        }

        std::vector<uint8_t> cq_ring(CQ_BSIZE, 0);
        auto *cqe = reinterpret_cast<struct mlx5_cqe64 *>(cq_ring.data());
        for (size_t i = 0; i < Q_DEPTH; ++i) {
            mlx5dv_set_cqe_owner(cqe++, 1);
        }

        if (flexio_copy_from_host(flexio_process_, cq_ring.data(), CQ_BSIZE, &cq_transf.cq_ring_daddr)) {
            std::cerr << "[Host] Failed to allocate CQ ring on DPA heap\n";
            return false;
        }
        return true;
    }

    struct flexio_mkey *create_mkey(flexio_uintptr_t daddr) {
        struct flexio_mkey_attr attr = {};
        attr.pd = process_pd_;
        attr.daddr = daddr;
        attr.len = Q_DATA_BSIZE;
        attr.access = IBV_ACCESS_LOCAL_WRITE;

        struct flexio_mkey *mkey = nullptr;
        if (flexio_device_mkey_create(flexio_process_, &attr, &mkey)) {
            return nullptr;
        }
        return mkey;
    }

    bool create_event_handler() {
        struct flexio_event_handler_attr attr = {};
        attr.host_stub_func = dpa_mirror_handler;
        attr.affinity.type = FLEXIO_AFFINITY_NONE;

        if (flexio_event_handler_create(flexio_process_, &attr, &event_handler_)) {
            std::cerr << "[Host] Failed to create FlexIO event handler\n";
            return false;
        }
        return true;
    }

    bool create_sq() {
        if (!alloc_cq_mem(sq_cq_transf_)) {
            return false;
        }

        uint32_t uar_id = flexio_uar_get_id(process_uar_);

        struct flexio_cq_attr sqcq_attr = {};
        sqcq_attr.log_cq_depth = LOG_CQ_DEPTH;
        sqcq_attr.element_type = FLEXIO_CQ_ELEMENT_TYPE_NON_DPA_CQ;
        sqcq_attr.uar_id = uar_id;
        sqcq_attr.cq_dbr_daddr = sq_cq_transf_.cq_dbr_daddr;
        sqcq_attr.cq_ring_qmem.daddr = sq_cq_transf_.cq_ring_daddr;

        if (flexio_cq_create(flexio_process_, nullptr, &sqcq_attr, &sq_cq_)) {
            std::cerr << "[Host] Failed to create SQ CQ\n";
            return false;
        }

        sq_cq_transf_.cq_num = flexio_cq_get_cq_num(sq_cq_);
        sq_cq_transf_.log_cq_depth = LOG_CQ_DEPTH;

        flexio_buf_dev_alloc(flexio_process_, Q_DATA_BSIZE, &sq_transf_.wqd_daddr);
        flexio_buf_dev_alloc(flexio_process_, WQ_RING_BSIZE, &sq_transf_.wq_ring_daddr);
        if (!sq_transf_.wqd_daddr || !sq_transf_.wq_ring_daddr) {
            std::cerr << "[Host] Failed to allocate SQ data/ring on DPA\n";
            return false;
        }

        struct flexio_wq_attr sq_attr = {};
        sq_attr.log_wq_depth = LOG_SQ_DEPTH;
        sq_attr.uar_id = uar_id;
        sq_attr.wq_ring_qmem.daddr = sq_transf_.wq_ring_daddr;
        sq_attr.pd = process_pd_;

        if (flexio_sq_create(flexio_process_, nullptr, sq_cq_transf_.cq_num, &sq_attr, &flexio_sq_)) {
            std::cerr << "[Host] Failed to create FlexIO SQ\n";
            return false;
        }

        sq_transf_.wq_num = flexio_sq_get_wq_num(flexio_sq_);

        sq_mkey_ = create_mkey(sq_transf_.wqd_daddr);
        if (!sq_mkey_) {
            std::cerr << "[Host] Failed to create SQ MKey\n";
            return false;
        }
        sq_transf_.wqd_mkey_id = flexio_mkey_get_id(sq_mkey_);

        return true;
    }

    bool create_rq() {
        if (!alloc_cq_mem(rq_cq_transf_)) {
            return false;
        }

        uint32_t uar_id = flexio_uar_get_id(process_uar_);

        struct flexio_cq_attr rqcq_attr = {};
        rqcq_attr.log_cq_depth = LOG_CQ_DEPTH;
        rqcq_attr.element_type = FLEXIO_CQ_ELEMENT_TYPE_DPA_THREAD;
        rqcq_attr.thread = flexio_event_handler_get_thread(event_handler_);
        rqcq_attr.uar_id = uar_id;
        rqcq_attr.cq_dbr_daddr = rq_cq_transf_.cq_dbr_daddr;
        rqcq_attr.cq_ring_qmem.daddr = rq_cq_transf_.cq_ring_daddr;

        if (flexio_cq_create(flexio_process_, nullptr, &rqcq_attr, &rq_cq_)) {
            std::cerr << "[Host] Failed to create RQ CQ\n";
            return false;
        }

        rq_cq_transf_.cq_num = flexio_cq_get_cq_num(rq_cq_);
        rq_cq_transf_.log_cq_depth = LOG_CQ_DEPTH;

        flexio_buf_dev_alloc(flexio_process_, Q_DATA_BSIZE, &rq_transf_.wqd_daddr);
        flexio_buf_dev_alloc(flexio_process_, WQ_RING_BSIZE, &rq_transf_.wq_ring_daddr);
        __be32 dbr[2] = {0, 0};
        flexio_copy_from_host(flexio_process_, dbr, sizeof(dbr), &rq_transf_.wq_dbr_daddr);

        if (!rq_transf_.wqd_daddr || !rq_transf_.wq_ring_daddr || !rq_transf_.wq_dbr_daddr) {
            std::cerr << "[Host] Failed to allocate RQ memory on DPA\n";
            return false;
        }

        rq_mkey_ = create_mkey(rq_transf_.wqd_daddr);
        if (!rq_mkey_) {
            std::cerr << "[Host] Failed to create RQ MKey\n";
            return false;
        }
        rq_transf_.wqd_mkey_id = flexio_mkey_get_id(rq_mkey_);

        // Initialize RQ ring with WQEs
        std::vector<struct mlx5_wqe_data_seg> rx_wqes(Q_DEPTH);
        flexio_uintptr_t curr_data_addr = rq_transf_.wqd_daddr;
        for (size_t i = 0; i < Q_DEPTH; ++i) {
            mlx5dv_set_data_seg(&rx_wqes[i], Q_DATA_ENTRY_BSIZE, rq_transf_.wqd_mkey_id, curr_data_addr);
            curr_data_addr += Q_DATA_ENTRY_BSIZE;
        }

        if (flexio_host2dev_memcpy(flexio_process_, rx_wqes.data(), WQ_RING_BSIZE, rq_transf_.wq_ring_daddr)) {
            std::cerr << "[Host] Failed to copy RQ WQEs to DPA\n";
            return false;
        }

        // Set RQ DBR to number of prepared WQEs
        dbr[0] = htobe32(Q_DEPTH & 0xFFFF);
        dbr[1] = 0;
        if (flexio_host2dev_memcpy(flexio_process_, dbr, sizeof(dbr), rq_transf_.wq_dbr_daddr)) {
            std::cerr << "[Host] Failed to copy RQ DBR to DPA\n";
            return false;
        }

        struct flexio_wq_attr rq_attr = {};
        rq_attr.log_wq_depth = LOG_RQ_DEPTH;
        rq_attr.pd = process_pd_;
        rq_attr.wq_dbr_qmem.memtype = FLEXIO_MEMTYPE_DPA;
        rq_attr.wq_dbr_qmem.daddr = rq_transf_.wq_dbr_daddr;
        rq_attr.wq_ring_qmem.daddr = rq_transf_.wq_ring_daddr;

        if (flexio_rq_create(flexio_process_, nullptr, rq_cq_transf_.cq_num, &rq_attr, &flexio_rq_)) {
            std::cerr << "[Host] Failed to create FlexIO RQ\n";
            return false;
        }

        rq_transf_.wq_num = flexio_rq_get_wq_num(flexio_rq_);
        return true;
    }

    bool setup_steering() {
        std::cout << "[Host] Configuring Flow Steering for UDP port " << udp_port_ << "...\n";
        struct mlx5dv_devx_obj *tir = flexio_rq_get_tir(flexio_rq_);
        if (!tir) {
            std::cerr << "[Host] Failed to get TIR from FlexIO RQ\n";
            return false;
        }

        if (!flow_mgr_.setup_rx_rule(ibv_ctx_, tir, udp_port_)) {
            std::cerr << "[Host] Failed to create RX flow rule\n";
            return false;
        }

        if (!nic_mode_) {
            std::cout << "[Host] Running in DPU mode: configuring TX vport forward rule for MAC 0x"
                      << std::hex << client_dmac_ << std::dec << "...\n";
            if (!flow_mgr_.setup_tx_rules(ibv_ctx_, client_dmac_)) {
                std::cerr << "[Host] Failed to create TX flow rules (DPU mode)\n";
                return false;
            }
        }
        return true;
    }

    bool copy_config_to_dpa() {
        struct host2dev_mirror_data config = {};
        config.rq_cq_transf = rq_cq_transf_;
        config.rq_transf = rq_transf_;
        config.sq_cq_transf = sq_cq_transf_;
        config.sq_transf = sq_transf_;
        config.target_udp_port = udp_port_;
        config.initialized = 0;

        if (flexio_copy_from_host(flexio_process_, &config, sizeof(config), &app_data_daddr_)) {
            std::cerr << "[Host] Failed to copy configuration to DPA\n";
            return false;
        }
        return true;
    }

    void teardown() {
        flow_mgr_.clear();

        if (flexio_process_ && app_data_daddr_) {
            flexio_buf_dev_free(flexio_process_, app_data_daddr_);
            app_data_daddr_ = 0;
        }

        if (sq_mkey_) {
            flexio_device_mkey_destroy(sq_mkey_);
            sq_mkey_ = nullptr;
        }
        if (flexio_sq_) {
            flexio_sq_destroy(flexio_sq_);
            flexio_sq_ = nullptr;
        }
        if (sq_transf_.wqd_daddr) {
            flexio_buf_dev_free(flexio_process_, sq_transf_.wqd_daddr);
        }
        if (sq_transf_.wq_ring_daddr) {
            flexio_buf_dev_free(flexio_process_, sq_transf_.wq_ring_daddr);
        }
        if (sq_cq_) {
            flexio_cq_destroy(sq_cq_);
            sq_cq_ = nullptr;
        }
        if (sq_cq_transf_.cq_dbr_daddr) {
            flexio_buf_dev_free(flexio_process_, sq_cq_transf_.cq_dbr_daddr);
        }
        if (sq_cq_transf_.cq_ring_daddr) {
            flexio_buf_dev_free(flexio_process_, sq_cq_transf_.cq_ring_daddr);
        }

        if (rq_mkey_) {
            flexio_device_mkey_destroy(rq_mkey_);
            rq_mkey_ = nullptr;
        }
        if (flexio_rq_) {
            flexio_rq_destroy(flexio_rq_);
            flexio_rq_ = nullptr;
        }
        if (rq_transf_.wqd_daddr) {
            flexio_buf_dev_free(flexio_process_, rq_transf_.wqd_daddr);
        }
        if (rq_transf_.wq_ring_daddr) {
            flexio_buf_dev_free(flexio_process_, rq_transf_.wq_ring_daddr);
        }
        if (rq_transf_.wq_dbr_daddr) {
            flexio_buf_dev_free(flexio_process_, rq_transf_.wq_dbr_daddr);
        }
        if (rq_cq_) {
            flexio_cq_destroy(rq_cq_);
            rq_cq_ = nullptr;
        }
        if (rq_cq_transf_.cq_dbr_daddr) {
            flexio_buf_dev_free(flexio_process_, rq_cq_transf_.cq_dbr_daddr);
        }
        if (rq_cq_transf_.cq_ring_daddr) {
            flexio_buf_dev_free(flexio_process_, rq_cq_transf_.cq_ring_daddr);
        }

        if (event_handler_) {
            flexio_event_handler_destroy(event_handler_);
            event_handler_ = nullptr;
        }

        if (msg_stream_) {
            flexio_msg_stream_destroy(msg_stream_);
            msg_stream_ = nullptr;
        }

        if (flexio_process_) {
            flexio_process_destroy(flexio_process_);
            flexio_process_ = nullptr;
        }

        if (ibv_ctx_) {
            ibv_close_device(ibv_ctx_);
            ibv_ctx_ = nullptr;
        }
    }

private:
    std::string device_name_;
    uint16_t udp_port_;
    bool nic_mode_;
    uint64_t client_dmac_{0};

    struct ibv_context *ibv_ctx_{nullptr};
    struct flexio_app *flexio_app_{nullptr};
    struct flexio_process *flexio_process_{nullptr};
    struct ibv_pd *process_pd_{nullptr};
    struct flexio_uar *process_uar_{nullptr};
    struct flexio_msg_stream *msg_stream_{nullptr};

    struct flexio_event_handler *event_handler_{nullptr};
    flexio_uintptr_t app_data_daddr_{0};

    struct app_transfer_cq sq_cq_transf_{};
    struct app_transfer_wq sq_transf_{};
    struct flexio_cq *sq_cq_{nullptr};
    struct flexio_sq *flexio_sq_{nullptr};
    struct flexio_mkey *sq_mkey_{nullptr};

    struct app_transfer_cq rq_cq_transf_{};
    struct app_transfer_wq rq_transf_{};
    struct flexio_cq *rq_cq_{nullptr};
    struct flexio_rq *flexio_rq_{nullptr};
    struct flexio_mkey *rq_mkey_{nullptr};

    dpa::FlowSteeringManager flow_mgr_;
};

int main(int argc, char **argv)
{
    std::signal(SIGINT, signal_handler);
    std::signal(SIGTERM, signal_handler);

    CLI::App app{"BlueField-3 DPA UDP Packet Mirroring Service"};

    std::string device = "mlx5_0";
    uint16_t port = 12345;
    std::string client_mac_str = "a0:88:c2:b6:14:1a"; // Default: fips1 RoCE MAC
#if defined(__x86_64__)
    bool nic_mode = true;
#else
    bool nic_mode = false;
#endif

    app.add_option("-d,--device", device, "InfiniBand / mlx5 device name")->capture_default_str();
    app.add_option("-p,--port", port, "UDP port to steer and mirror on the DPA")->capture_default_str();
    app.add_option("-m,--client-mac", client_mac_str, "Client MAC address for TX forwarding in DPU mode")->capture_default_str();
    app.add_flag("--nic-mode,!--dpu-mode", nic_mode, "Run in NIC/Host mode (default on x86) vs DPU mode (default on ARM)");

    CLI11_PARSE(app, argc, argv);

    // Parse MAC string into 64-bit int
    uint64_t client_dmac = 0;
    unsigned int m[6];
    if (std::sscanf(client_mac_str.c_str(), "%x:%x:%x:%x:%x:%x",
                    &m[0], &m[1], &m[2], &m[3], &m[4], &m[5]) == 6) {
        for (int i = 0; i < 6; ++i) {
            client_dmac = (client_dmac << 8) | (m[i] & 0xFF);
        }
    }

    DpaMirrorApp mirror_app(device, port, nic_mode, client_dmac);
    if (!mirror_app.initialize()) {
        std::cerr << "[Host] Initialization failed. Exiting.\n";
        return 1;
    }

    if (!mirror_app.run()) {
        std::cerr << "[Host] Runtime error encountered.\n";
        return 1;
    }

    std::cout << "[Host] Clean shutdown complete.\n";
    return 0;
}

